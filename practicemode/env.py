"""Load a local .env file into the environment (no third-party dependency)."""
import os


def load_env_file(path):
    """Read KEY=VALUE lines from path. Variables already set in the real
    environment win, so a shell `export` or hosting config overrides .env."""
    if not path.is_file():
        return
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.removeprefix("export ").strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
            value = value[1:-1]
        if key:
            os.environ.setdefault(key, value)
